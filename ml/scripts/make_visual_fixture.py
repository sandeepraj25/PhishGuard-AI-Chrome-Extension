"""Writes the e2e fixture for Layer 3: a look-alike of the FICTIONAL ExampleBank login page whose
logo + name are an image (no brand text in the DOM) and whose form posts to its own domain, so
Layers 1-2 have little to go on and only the visual model can recognise the imitation."""
from __future__ import annotations

import random

import _common  # noqa: F401
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
from phishguard_ml.paths import REPO

import make_visual_pages as mvp  # noqa: E402


def main() -> None:
    brand = next(b for b in mvp.BRANDS if b["id"] == "examplebank")
    r = random.Random(1234)
    while True:  # deterministic: first seeded clone that uses an image logo and no banner text
        html = mvp.page(brand, r, "clone")
        if "data:image/png" in html and "class=\"warn\"" not in html:
            break
    # Ordinary-looking footer links so the page model alone does not decide the case.
    footer = "<footer style='text-align:center;font-size:12px'>" + " · ".join(
        f"<a href='/{p}'>{p.title()}</a>" for p in ("help", "privacy", "terms", "security", "contact", "branches",
                                                     "careers", "about")) + "</footer>"
    html = html.replace("</body>", footer + "</body>")
    out = REPO / "extension/tests/fixtures/sites/examplebank_visual_clone.html"
    out.write_text("<!-- FICTIONAL brand look-alike for the Layer 3 e2e test (generated by "
                   "ml/scripts/make_visual_fixture.py). -->\n" + html, encoding="utf-8")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
